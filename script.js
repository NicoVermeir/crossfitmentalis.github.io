const menuButton = document.querySelector(".menu-toggle");
const menuLabel = menuButton.querySelector(".sr-only");
const navigation = document.querySelector(".site-nav");
const languageButtons = document.querySelectorAll("[data-language]");
let currentLanguage = "nl";

function setMenuLabel(isOpen) {
  menuLabel.textContent = translations[currentLanguage][isOpen ? "menuClose" : "menuOpen"];
}

function closeMenu() {
  navigation.classList.remove("open");
  document.body.classList.remove("menu-open");
  menuButton.setAttribute("aria-expanded", "false");
  setMenuLabel(false);
}

function applyLanguage(language) {
  currentLanguage = translations[language] ? language : "nl";
  const copy = translations[currentLanguage];

  document.documentElement.lang = currentLanguage;
  document.title = copy.pageTitle;
  document.querySelector('meta[name="description"]').content = copy.metaDescription;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = copy[element.dataset.i18n];
    if (value === undefined) return;
    element.textContent = value;
  });
  document.querySelectorAll("[data-i18n-html]").forEach((element) => {
    const value = copy[element.dataset.i18nHtml];
    if (value === undefined) return;
    element.innerHTML = value;
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
    const value = copy[element.dataset.i18nAria];
    if (value === undefined) return;
    element.setAttribute("aria-label", value);
  });
  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const value = copy[element.dataset.i18nAlt];
    if (value === undefined) return;
    element.alt = value;
  });
  document.querySelectorAll("[data-i18n-title]").forEach((element) => {
    const value = copy[element.dataset.i18nTitle];
    if (value === undefined) return;
    element.title = value;
  });
  document.querySelectorAll("[data-label-key]").forEach((element) => {
    const value = copy[element.dataset.labelKey];
    if (value === undefined) return;
    element.dataset.label = value;
  });
  languageButtons.forEach((button) => {
    button.setAttribute("aria-pressed", String(button.dataset.language === currentLanguage));
  });
  setMenuLabel(navigation.classList.contains("open"));
}

menuButton.addEventListener("click", () => {
  const isOpen = navigation.classList.toggle("open");
  document.body.classList.toggle("menu-open", isOpen);
  menuButton.setAttribute("aria-expanded", String(isOpen));
  setMenuLabel(isOpen);
});

navigation.querySelectorAll("a").forEach((link) => {
  link.addEventListener("click", closeMenu);
});

languageButtons.forEach((button) => {
  button.addEventListener("click", () => {
    applyLanguage(button.dataset.language);
  });
});

window.addEventListener("resize", () => {
  if (window.innerWidth > 1080) {
    closeMenu();
  }
});

document.addEventListener("keydown", (event) => {
  if (event.key === "Escape" && navigation.classList.contains("open")) {
    closeMenu();
    menuButton.focus();
  }
});

document.querySelector("#year").textContent = new Date().getFullYear();
applyLanguage("nl");
